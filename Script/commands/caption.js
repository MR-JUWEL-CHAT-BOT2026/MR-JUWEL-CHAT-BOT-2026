let usedIndex = 0;

function getRandomCaption() {
  if (usedIndex < 7) {
    return tl[usedIndex++];
  } else {
    const randomIndex = Math.floor(Math.random() * (tl.length - 7)) + 7;
    return tl[randomIndex];
  }
}

module.exports.handleEvent = async function ({ api, event }) {
  const { threadID, messageID, body } = event;
  if (!body) return;

  if (body.trim().toLowerCase() === module.exports.config.name) {
    const rand = getRandomCaption();
    return api.sendMessage({ body: rand }, threadID, messageID);
  }
};

module.exports.run = async function ({ api, event }) {
  const { threadID, messageID } = event;
  const rand = getRandomCaption();
  return api.sendMessage({ body: rand }, threadID, messageID);
};
